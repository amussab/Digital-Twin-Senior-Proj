"""Export the existing Python envelope design and independent MCU references.

Uses the existing signed band-pass reference samples as the component's input.
The 3600-RPM mode tests a window length; these are not physical 3600-RPM recordings.
Run with the coe_pipeline environment and --python-project PATH --firmware-project PATH.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

import numpy as np
from scipy.signal import sosfilt, sosfreqz


def literal(value):
    """Format a float32 value as a reproducible C floating-point literal."""
    return f"{float(np.float32(value)):.9e}f"


def rows(values):
    """Format an array as six C literals per line."""
    return "\n".join("        " + ", ".join(literal(v) for v in values[i:i+6]) + ","
                     for i in range(0, len(values), 6))


def main():
    """Export coefficients and continuously filtered, decimated window references."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--python-project", type=Path, required=True)
    parser.add_argument("--firmware-project", type=Path, required=True)
    args = parser.parse_args()
    sys.path.insert(0, str(args.python_project.resolve()))
    from steps.step_04.step_04_envelope import design_envelope_lowpass, apply_envelope_lowpass, rectify_signal
    from steps.step_05.step_05_decimation import decimate_envelope

    data = (args.firmware_project / "CM7/TestData/fixtures/bandpass_fixtures.h").read_bytes()
    match = re.search(r"bandpass_test_expected\[4\]\[1024\] = \{(.*?)\n\};", data.decode(), re.S)
    if match is None:
        raise ValueError("Could not locate the existing signed band-pass fixtures.")
    values = re.findall(r"([-+]?\d+\.\d+e[-+]\d+)f", match.group(1))
    if len(values) != 4096:
        raise ValueError("Expected exactly four 1024-sample input arrays.")
    snippets = np.array(values, dtype=np.float32).reshape(4, 1024)
    sos64 = design_envelope_lowpass(30000, 350, 1250)
    sos32 = sos64.astype(np.float32)
    if sos64.shape != (4, 6) or not np.all(sos64[:, 3] == 1):
        raise ValueError("Expected four normalized low-pass sections.")
    pole_radius = max(max(abs(np.roots(s[3:].astype(np.float64)))) for s in sos32)
    if pole_radius >= 1:
        raise ValueError("The quantized filter is unstable.")
    frequencies = np.array([0., 350., 1250., 2500.])
    _, response = sosfreqz(sos32.astype(np.float64), worN=frequencies, fs=30000)
    response_db = 20 * np.log10(abs(response))
    # Allow the measured, tiny float32 coefficient deviation from the 0.1-dB target.
    if response_db[1] < -0.101 or response_db[2] > -60 or response_db[3] > -60:
        raise ValueError("Quantized low-pass response exceeds the design tolerance.")
    cmsis = sos32[:, [0, 1, 2, 4, 5]].copy()
    cmsis[:, 3:] *= -1
    if not np.array_equal(cmsis[:, 3:], -sos32[:, 4:]):
        raise ValueError("CMSIS feedback sign conversion failed.")

    cm7 = Path(__file__).resolve().parents[2]
    coefficient_lines = [
        "/* Envelope low-pass coefficients; generated by TestData/generators/generate_envelope_fixtures.py. */",
        "/* Python step 04: Butterworth order 7, passband 350 Hz, stopband 1250 Hz. */",
        "#ifndef COE_ENVELOPE_COEFFICIENTS_H", "#define COE_ENVELOPE_COEFFICIENTS_H",
        "#define ENVELOPE_DESIGN_SAMPLE_RATE_HZ 30000U",
        "#define ENVELOPE_DESIGN_PASSBAND_HZ 350U",
        "#define ENVELOPE_DESIGN_STOPBAND_HZ 1250U",
        "#define ENVELOPE_DESIGN_DECIMATION_FACTOR 6U",
        "#define ENVELOPE_DESIGN_SECTIONS 4U",
        "/* CMSIS order: b0,b1,b2,-a1,-a2 for each section (plus feedback). */",
        "static const float envelope_cmsis_coefficients[20] = {",
    ]
    for section in cmsis:
        coefficient_lines.append("    " + ", ".join(literal(v) for v in section) + ",")
    coefficient_lines += ["};", "#endif", ""]
    (cm7 / "App/dsp/envelope/envelope_coefficients.h").write_text("\n".join(coefficient_lines), encoding="utf-8")

    header = [
        "/* Independent Python step 04/05 outputs for exact float32 component inputs. */",
        "/* Functional window tests; repeated snippets are not physical 3600-RPM data. */",
        "#ifndef COE_ENVELOPE_FIXTURES_H", "#define COE_ENVELOPE_FIXTURES_H",
    ]
    counts, max_errors = [], []
    for rpm in (1750, 3600):
        count = round(30000 * 60 * 20 / rpm)
        mode_counts = []
        mode_errors = []
        expected = [[], []]
        for channel in snippets:
            signed = np.tile(channel, (2 * count + 1023) // 1024)[:2*count]
            rectified = rectify_signal(signed.astype(np.float64))
            filtered64, _ = apply_envelope_lowpass(rectified, sos64)
            filtered32 = sosfilt(sos32, rectify_signal(signed))
            error = np.abs(filtered32.astype(np.float64) - filtered64)
            if np.any(error > 2e-5 * (1 + np.abs(filtered64))):
                raise ValueError("Float32 envelope exceeds the unchanged sample tolerance.")
            mode_errors.append(float(np.max(error)))
            phase = 0
            for window in range(2):
                reduced, phase = decimate_envelope(filtered64[window*count:(window+1)*count], 6, phase)
                expected[window].append(reduced.astype(np.float32))
        for window in range(2):
            output_count = len(expected[window][0])
            if any(len(x) != output_count for x in expected[window]):
                raise ValueError("All channels must share the same selection phase.")
            mode_counts.append(output_count)
            header.append(f"static const float envelope_expected_{rpm}_{window}[4][{output_count}] = {{")
            for channel in expected[window]:
                header += ["    {", rows(channel), "    },"]
            header.append("};")
        counts.append(mode_counts)
        max_errors.append(mode_errors)
    header += ["static const size_t envelope_expected_counts[2][2] = {",
               "    {" + ", ".join(f"{n}U" for n in counts[0]) + "},",
               "    {" + ", ".join(f"{n}U" for n in counts[1]) + "},", "};",
               "static const float *const envelope_expected_windows[2][2][4] = {"]
    for rpm in (1750, 3600):
        header.append("    {")
        for window in range(2):
            header.append("        {" + ", ".join(f"envelope_expected_{rpm}_{window}[{c}]" for c in range(4)) + "},")
        header.append("    },")
    header += ["};", "#endif", ""]
    (cm7 / "TestData/fixtures/envelope_fixtures.h").write_text("\n".join(header), encoding="utf-8")
    report = {
        "source_fixture_sha256": hashlib.sha256(data).hexdigest(),
        "input": "repeat exact float32 bandpass_test_expected snippets; independent envelope component test",
        "reference": "unchanged Python steps 04 and 05, float64 filter, continuous state and phase",
        "sample_rate_hz": 30000, "envelope_rate_hz": 5000, "decimation_factor": 6,
        "passband_hz": 350, "stopband_hz": 1250, "butterworth_order": 7, "sections": 4,
        "max_quantized_pole_radius": float(pole_radius),
        "quantized_response_db": dict(zip(frequencies.astype(int).astype(str), response_db.tolist())),
        "samples_per_window": [20571, 10000], "retained_per_consecutive_window": counts,
        "max_scipy_float32_error_g": max_errors,
        "tolerance": "abs(error) <= 2e-5 * (1 + abs(reference))",
        "initial_state": "zero at stream startup only; phase zero at sample index zero",
        "mcu_execution": "pending board verification",
    }
    (cm7 / "TestData/fixtures/envelope_reference_report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print("Exported four envelope sections and continuous two-window references.")
    print("Retained counts:", counts, "Maximum SciPy float32 errors:", max_errors)


if __name__ == "__main__":
    main()
