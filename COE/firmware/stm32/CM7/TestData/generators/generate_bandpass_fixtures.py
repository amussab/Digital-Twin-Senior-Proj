"""Export the Python filter design and MCU test fixtures; not MCU runtime code.

Run with the existing coe_pipeline Python environment and --python-project PATH.
Generated files are saved relative to this script's firmware CM7 directory.
"""
import argparse
import importlib
from pathlib import Path
import json
import sys

import numpy as np
from scipy.signal import sosfilt, sosfreqz


def literal(value):
    """Format a float32 value as a reproducible C floating-point literal."""
    return f"{float(np.float32(value)):.9e}f"


def array_rows(values):
    """Format an array of values as six C literals per row."""
    return "\n".join("        " + ", ".join(literal(v) for v in values[i:i+6]) + ","
                     for i in range(0, len(values), 6))


def main():
    """Export coefficients, recorded fixtures and the numerical comparison report."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--python-project", type=Path, required=True)
    args = parser.parse_args()
    sys.path.insert(0, str(args.python_project.resolve()))
    signal_module = importlib.import_module("steps.step_01.step_01_signal")
    bandpass_module = importlib.import_module("steps.step_02.step_02_bandpass")
    load_signal = signal_module.load_signal
    resample_signal = signal_module.resample_signal
    design_bandpass = bandpass_module.design_bandpass
    apply_bandpass = bandpass_module.apply_bandpass

    cm7 = Path(__file__).resolve().parents[2]
    sos64 = np.asarray(design_bandpass(30000, 2000, 8000), dtype=np.float64)
    sos32 = np.asarray(sos64, dtype=np.float32)
    if sos64.shape != (4, 6) or not np.all(sos64[:, 3] == 1):
        raise ValueError("Expected four normalized biquads.")
    for section in sos32:
        if np.max(np.abs(np.roots(section[3:].astype(np.float64)))) >= 1:
            raise ValueError("Quantized filter is unstable.")

    coefficient_lines = [
        "/* Band-pass coefficient tables for the production CMSIS-DSP filter. */",
        "/* Generated by TestData/generators/generate_bandpass_fixtures.py. */",
        "/* butter(4, [2000,8000], fs=30000, btype='bandpass', output='sos'). */",
        "#ifndef COE_BANDPASS_COEFFICIENTS_H", "#define COE_BANDPASS_COEFFICIENTS_H",
        "#define BANDPASS_DESIGN_SAMPLE_RATE_HZ 30000U",
        "#define BANDPASS_DESIGN_LOW_HZ 2000U",
        "#define BANDPASS_DESIGN_HIGH_HZ 8000U",
        "#define BANDPASS_DESIGN_SECTIONS 4U",
        "/* Each row: b0, b1, b2, a1, a2; conventional minus feedback. */",
        "static const float bandpass_sos[4][5] = {",
    ]
    for section in sos32:
        coefficient_lines.append("    {" + ", ".join(literal(v) for v in section[[0,1,2,4,5]]) + "},")
    coefficient_lines += ["};",
        "/* CMSIS plus-feedback convention: b0, b1, b2, -a1, -a2 per stage. */",
        "static const float bandpass_cmsis_coefficients[20] = {"]
    cmsis = sos32[:, [0, 1, 2, 4, 5]].copy()
    cmsis[:, 3:] *= -1
    if not np.array_equal(cmsis[:, :3], sos32[:, :3]) or not np.array_equal(cmsis[:, 3:], -sos32[:, 4:]):
        raise ValueError("CMSIS feedback sign conversion failed.")
    for section in cmsis:
        coefficient_lines.append("    " + ", ".join(literal(v) for v in section) + ",")
    coefficient_lines += ["};", "#endif", ""]
    (cm7 / "App" / "dsp" / "bandpass" / "bandpass_coefficients.h").write_text("\n".join(coefficient_lines), encoding="utf-8")

    recordings = [
        ("healthy_1750rpm.mat", "X099_DE_time"),
        ("outer_race_1750rpm.mat", "X137_DE_time"),
        ("inner_race_1750rpm.mat", "X111_DE_time"),
        ("ball_1750rpm.mat", "X124_DE_time"),
    ]
    inputs, expected, float32_errors = [], [], []
    for file, key in recordings:
        # Match the offline preparation: resample the full recording first.
        prepared = resample_signal(load_signal(args.python_project / "data" / "cwru" / file, key), 48000, 30000)
        samples = prepared[:1024].astype(np.float32)
        if len(samples) != 1024 or not np.all(np.isfinite(samples)):
            raise ValueError("Invalid fixture samples.")
        # Reference uses the original float64 design on exactly these float32 inputs.
        filtered64, _ = apply_bandpass(samples.astype(np.float64), sos64)
        filtered32 = np.asarray(sosfilt(sos32, samples))
        error = np.abs(filtered32.astype(np.float64) - filtered64)
        if np.any(error > 2e-5 * (1 + np.abs(filtered64))):
            raise ValueError("Float32 quantization exceeds the test tolerance.")
        inputs.append(samples)
        expected.append(filtered64.astype(np.float32))
        float32_errors.append(float(np.max(error)))

    impulse = np.zeros(128)
    impulse[0] = 1
    impulse_expected, _ = apply_bandpass(impulse, sos64)
    header = ["/* Generated test data, not an application component. */",
              "/* Four separate CWRU experiments; not simultaneous machine channels. */",
              "#ifndef COE_BANDPASS_FIXTURES_H", "#define COE_BANDPASS_FIXTURES_H",
              "#define BANDPASS_FIXTURE_SAMPLES 1024U",
              "#define BANDPASS_FIXTURE_CHANNELS 4U"]
    for name, values in (("bandpass_test_input", inputs), ("bandpass_test_expected", expected)):
        header.append(f"static const float {name}[4][1024] = {{")
        for channel in values:
            header += ["    {", array_rows(channel), "    },"]
        header += ["};"]
    header += ["static const float bandpass_impulse_expected[128] = {",
               array_rows(impulse_expected), "};", "#endif", ""]
    (cm7 / "TestData" / "fixtures" / "bandpass_fixtures.h").write_text("\n".join(header), encoding="utf-8")

    frequencies = np.asarray([500., 2000., 4000., 8000., 12000.], dtype=np.float64)
    _, response = sosfreqz(sos32.astype(np.float64), worN=frequencies, fs=30000)
    response = np.asarray(response)
    magnitude = np.abs(response)
    # Validate the exported design's cutoff and passband behaviour separately.
    if not np.allclose(magnitude[[1, 3]], 1 / np.sqrt(2), atol=2e-6):
        raise ValueError("Quantized cutoff response does not match -3 dB.")
    report = {
        "sample_rate_hz": 30000, "cutoffs_hz": [2000,8000],
        "sections": 4, "overall_order": 8, "samples_per_fixture": 1024,
        "initial_state": "zero", "inputs_rounded_to": "float32",
        "reference": "unchanged Python step 02, original float64 coefficients",
        "max_scipy_float32_error_g": float32_errors,
        "frequency_response": {str(int(f)): float(h) for f, h in zip(frequencies, magnitude)},
        "tolerance": "abs(error) <= 2e-5 * (1 + abs(expected))",
        "source_files": [file for file, _ in recordings],
        "mcu_execution": "pending board verification",
    }
    (cm7 / "TestData" / "fixtures" / "bandpass_reference_report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print("Exported four biquads and 4 x 1024 CWRU input/reference fixtures.")
    print("Maximum SciPy float32 errors (g):", float32_errors)


if __name__ == "__main__":
    main()
